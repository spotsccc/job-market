/** Пост для модели: автор с подписью помогает понять, кто нанимает и в какую компанию. */
export function formatPost(post: LinkedinPost): string {
  const headline = post.author.headline === null ? '' : `\nПодпись автора: ${post.author.headline}`;
  return `<post>
Автор: ${post.author.name}${headline}
Ссылка на автора: ${post.author.url}
Опубликован: ${post.postedAt.toISOString()}

${post.content}
</post>`;
}
