-- Бесплатные источники — все, кроме linkedin (за его посты платим Apify), — опрашиваются каждый
-- час. Тик идёт раз в час и сдвигает next_run_at на «время тика + interval_minutes». Интервал
-- 50 минут, а не 60: следующий тик может начаться на несколько секунд раньше, и при 60 минутах
-- источник пропускал бы час. Источники без ошибок подряд, которых ждать до суток, становятся
-- готовы к ближайшему тику; у источников с ошибками пауза после неудачи остаётся прежней.
UPDATE "sources"
SET "interval_minutes" = 50,
  "next_run_at" = CASE
    WHEN "consecutive_failures" = 0 THEN LEAST("next_run_at", now())
    ELSE "next_run_at"
  END
WHERE "connector" <> 'linkedin';
