/**
 * Нормализует название места для сравнения: одна и та же функция строит
 * `geo_aliases.normalized` в генераторе и готовит текст запроса, поэтому разные
 * написания одного названия сходятся в одну строку.
 *
 * Шаги по порядку:
 * 1. NFKD раскладывает буквы с диакритикой на букву и знак: «ü» → «u» + «¨», «й» → «и» + «˘».
 * 2. Знаки (`\p{M}`) убираются: «München» → «Munchen», «Айрес» → «Аирес». Это до
 *    замены не-букв, иначе знаки превратились бы в пробелы.
 * 3. Нижний регистр, затем «ß» → «ss» (после регистра — так ловится и «ẞ»). «ё» уже
 *    стала «е» на шагах 1–2.
 * 4. Всё, кроме букв и цифр, — пробел; пробелы схлопываются и по краям убираются.
 *
 * «Санкт-Петербург» → «санкт петербург», «  St. Petersburg » → «st petersburg»,
 * «---» → пустая строка.
 */
export function normalizeName(name: string): string {
  return name
    .normalize('NFKD')
    .replaceAll(/\p{M}/gu, '')
    .toLowerCase()
    .replaceAll('ß', 'ss')
    .replaceAll(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();
}
