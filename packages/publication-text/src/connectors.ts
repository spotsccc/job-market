import type { Connector } from '@job-market/db/values';

/**
 * Как модель видит публикацию каждого коннектора: метка источника в тексте для модели и
 * абзац инструкции о том, кто автор и кто нанимает. Метка зависит от коннектора, а не от
 * площадки источника: коннектор говорит, что за текст перед моделью. `Record` по типу
 * `Connector`, поэтому новый коннектор без метки и абзаца не компилируется.
 */
export const CONNECTOR_LABELS: Readonly<
  Record<Connector, { readonly label: string; readonly note: string }>
> = {
  linkedin: {
    label: 'LinkedIn',
    note: 'пишет сам нанимающий: рекрутёр, менеджер или компания',
  },
  'open-telegram': {
    label: 'Telegram-канал',
    note: 'каналы-агрегаторы вакансий. Автор поста — канал, а не работодатель: компанию, условия и способ отклика бери из текста поста',
  },
  greenhouse: {
    label: 'Доска вакансий компании',
    note: 'вакансию опубликовал сам работодатель на своей доске вакансий. Компания — автор публикации',
  },
};

/** Абзац инструкции модели об источниках: по строке на коннектор. */
export const CONNECTORS_NOTE = `Посты приходят из таких источников:
${Object.values(CONNECTOR_LABELS)
  .map(({ label, note }) => `- ${label} — ${note}.`)
  .join('\n')}`;
